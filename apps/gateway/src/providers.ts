import { OpensipsProvider, SubscriberProvisioner, type EventsLogger, type SubscriberProvisionerOptions } from '@twake/provider-opensips'
import type { ProviderContext, ProviderFactory } from '@twake/telephony-provider-sdk'
import { SipSecrets } from './sip-secrets.js'
import type { Store } from './store/types.js'

/** "env:NAME" -> value of the environment variable. A vault scheme would plug in here. */
export const resolveRef = (ref: string, env: NodeJS.ProcessEnv = process.env): string => {
  const m = /^env:([A-Z0-9_]+)$/.exec(ref)
  if (!m) throw new Error(`Unsupported secret reference: ${ref.split(':')[0]}:…`)
  const value = env[m[1]!]
  if (value === undefined) throw new Error(`Secret reference ${ref} is not set`)
  return value
}

/** What is stored in provider_configs for an OpenSIPS provider. The database holding `subscriber` is a reference. */
export interface StoredOpensipsConfig {
  /** Public SIP-over-WebSocket URL browsers register to. */
  websocketUrl: string
  /** SIP domain of the accounts and digest realm. */
  domain: string
  iceServers?: { urls: string[]; username?: string; credential?: string }[]
  /** `env:NAME` holding the URL of the database OpenSIPS's auth_db reads; may be the Gateway's own. */
  subscriberDbUrlRef: string
  /**
   * Where to hear OpenSIPS (ADR 0011): its MI socket (`udp:host:port` of `mi_datagram`), the address this Gateway
   * listens on for the events (`host[:port]`) and, when OpenSIPS must be given another one (a wildcard `listen`, a
   * container), the address it sends them to (`advertise`), and the addresses they may come from besides the MI
   * host (`from`: OpenSIPS sends them from the address its kernel picks). Without it: no presence, no history.
   */
  events?: { miUrl: string; listen?: string; advertise?: string; from?: string[] }
}

export interface OpensipsFactoryDeps {
  store: Store
  /** Encryption key of the SIP secrets kept by the Gateway; without it the provider cannot hand out credentials. */
  key?: Buffer
  env?: NodeJS.ProcessEnv
  /** Test seam: builds the provisioner from its options. */
  provisionerFor?: (opts: SubscriberProvisionerOptions) => SubscriberProvisioner
  /** Where the provider logs what OpenSIPS tells it; the console by default. */
  logger?: EventsLogger
}

/** Which database a URL names (host, port, database), whoever connects to it: what two tenants may not share. */
const databaseOf = (url: string) => {
  try {
    const u = new URL(url)
    return `${u.hostname.toLowerCase()}:${u.port || '5432'}${u.pathname}`
  } catch {
    return url
  }
}

/**
 * Builds OpenSIPS providers from their stored configuration. The SIP secrets are generated by the Gateway, kept
 * encrypted in its store and written as digest hashes into OpenSIPS's `subscriber` table, whose schema is checked
 * (and created when missing: dev and CI stacks share one fresh database) as soon as the provider is built, so a
 * wrong database shows in the Gateway's log at start-up and not at the first call.
 */
export const storedOpensipsFactory = ({ store, key, env = process.env, provisionerFor = opts => new SubscriberProvisioner(opts), logger }: OpensipsFactoryDeps): ProviderFactory<StoredOpensipsConfig> => {
  // The tenant each OpenSIPS database serves: `call_rules` is keyed by extension alone (as OpenSIPS reads it), so
  // two tenants on one database would overwrite each other's rules. One OpenSIPS (and its database) per tenant.
  const tenantOf = new Map<string, string>()
  return {
    type: 'opensips',
    create(config, context?: ProviderContext) {
      const tenantId = context?.tenantId ?? 'default'
      if (!key) throw new Error('SECRETS_KEY is required for the OpenSIPS provider (it encrypts the SIP secrets)')
      const databaseUrl = resolveRef(config.subscriberDbUrlRef, env)
      const database = databaseOf(databaseUrl)
      const holder = tenantOf.get(database)
      if (holder !== undefined && holder !== tenantId) throw new Error(`The OpenSIPS database of tenant ${tenantId} already serves tenant ${holder}: each tenant needs its own OpenSIPS and database`)
      tenantOf.set(database, tenantId)
      const provisioner = provisionerFor({ databaseUrl, realm: config.domain })
      let schema: Promise<void> | undefined
      const ensureSchema = () =>
        (schema ??= provisioner.ensureSchema().catch(err => {
          // Tried again at the next session: the database may simply not be up yet.
          schema = undefined
          throw err
        }))
      ensureSchema().catch((err: unknown) => console.error(`OpenSIPS subscriber database of tenant ${tenantId} not ready: ${err instanceof Error ? err.message : String(err)}`))
      const secrets = new SipSecrets({
        store,
        key,
        provisioner: {
          async setSipSecret(extension, secret) {
            await ensureSchema()
            await provisioner.setSipSecret(extension, secret)
          }
        }
      })
      return new OpensipsProvider({
        websocketUrl: config.websocketUrl,
        domain: config.domain,
        ...(config.iceServers ? { iceServers: config.iceServers } : {}),
        sipSecretFor: async extension => {
          const mapping = await store.getMappingByExtension(tenantId, extension)
          if (!mapping) throw Object.assign(new Error('Extension is not mapped to a user'), { statusCode: 404 })
          return secrets.getOrCreate(tenantId, mapping.userId, extension)
        },
        onClose: () => {
          if (tenantOf.get(database) === tenantId) tenantOf.delete(database)
          return provisioner.close()
        },
        // The forwards and "do not disturb" OpenSIPS reads, in the same database as `subscriber` (ADR 0013).
        callRules: provisioner.callRules({ ready: ensureSchema, tenantId, holderOf: async extension => (await store.getMappingByExtension(tenantId, extension))?.userId }),
        // The ring groups and the directory names OpenSIPS reads, in the same database too (ADR 0014).
        callGroups: provisioner.callGroups({ ready: ensureSchema, tenantId }),
        ...(config.events ? { events: config.events } : {}),
        ...(logger ? { logger } : {})
      })
    }
  }
}
